// Regenerates percentiles.js by scanning all 1,000,001 possible rolls
// (0..1,000,000) through badges.js's evaluateRoll() and tallying how many
// numbers land at or below each possible EP total.
//
// Run whenever badges.js's badge list, EP values, or family rules change:
//   node scripts/gen-percentiles.js
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const badgesPath = path.join(__dirname, "..", "badges.js");
const outPath = path.join(__dirname, "..", "percentiles.js");

const code = fs.readFileSync(badgesPath, "utf8") + "\nthis.evaluateRoll = evaluateRoll;";
const sandbox = {};
vm.createContext(sandbox);
vm.runInContext(code, sandbox);

const TOTAL = 1000001;
const counts = new Map();

for (let n = 0; n < TOTAL; n++) {
  const ep = sandbox.evaluateRoll(n).ep;
  counts.set(ep, (counts.get(ep) || 0) + 1);
}

const distinctEps = [...counts.keys()].sort((a, b) => a - b);
let cumulative = 0;
const table = [];
for (const ep of distinctEps) {
  cumulative += counts.get(ep);
  table.push([ep, cumulative]);
}

const js = `// Auto-generated by scripts/gen-percentiles.js — do not edit by hand.
// Scans all 1,000,001 possible rolls (0..1,000,000) through badges.js's
// evaluateRoll() and tallies how many numbers land at or below each possible
// EP total. Regenerate with \`node scripts/gen-percentiles.js\` whenever
// badges.js's badge list, EP values, or family rules change.
//
// PERCENTILE_TABLE: [ep, cumulativeCount] pairs, sorted ascending by ep.
// cumulativeCount = how many of the 1,000,001 possible rolls score <= ep.
const PERCENTILE_TOTAL = ${TOTAL};
const PERCENTILE_TABLE = ${JSON.stringify(table)};

// Percent of all possible rolls that score at or below \`ep\` (0-100).
function percentileOf(ep) {
  const t = PERCENTILE_TABLE;
  let lo = 0, hi = t.length - 1, ans = 0;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    if (t[mid][0] <= ep) { ans = mid; lo = mid + 1; }
    else hi = mid - 1;
  }
  return (t[ans][1] / PERCENTILE_TOTAL) * 100;
}
`;

fs.writeFileSync(outPath, js);
console.log(`Scanned ${TOTAL} rolls, ${distinctEps.length} distinct EP totals.`);
console.log(`Wrote ${outPath} (${fs.statSync(outPath).size.toLocaleString()} bytes).`);
